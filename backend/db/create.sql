create table public.items (
  id bigint generated by default as identity not null,
  restaurant character varying not null,
  name character varying null,
  serving_size_g real null,
  kcal real null,
  total_fat_g real null,
  saturated_fat_g real null,
  trans_fat_g real null,
  cholesterol_mg real null,
  sodium_mg real null,
  carbs_g real null,
  fiber_g real null,
  sugars_g real null,
  protein_g real null,
  constraint items_pkey primary key (id)
) TABLESPACE pg_default;

create table public.meal_plans (
  id uuid not null default gen_random_uuid (),
  plan character varying(20) not null,
  total numeric(10, 2) not null,
  weekly numeric(10, 2) not null,
  daily numeric(10, 2) not null,
  constraint meal_plans_pkey primary key (id)
) TABLESPACE pg_default;

-- Student Identity Information
-- References Supabase Auth
CREATE TABLE public.users (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    netid VARCHAR(50) UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- make a trigger where every new user in auth.users gets added to users table
drop trigger if exists "on_auth_user_created" on auth.users;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.users (id, netid, first_name, last_name, email, created_at)
  values (
    new.id, 
    (new.raw_user_meta_data ->> 'netid'),
    (new.raw_user_meta_data ->> 'first_name'),
    (new.raw_user_meta_data ->> 'last_name'),
    new.email, 
    new.created_at
  );
  return new;
end;
$$;

create trigger "on_auth_user_created"
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Student Nutritional Profiles
CREATE TABLE public.user_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    age INT NOT NULL CHECK (age > 0),
    height_cm NUMERIC(6,2) NOT NULL,
    body_weight_kg NUMERIC(6,2) NOT NULL,
    activity_level INT NOT NULL CHECK (activity_level BETWEEN 0 AND 7),
    goal VARCHAR(50) NOT NULL,
    meal_plan_id UUID REFERENCES meal_plans(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


-- 3. Food Logging
create table public.meal_logs (
  id uuid not null default gen_random_uuid (),
  user_id uuid not null,
  item_id bigint not null,
  meal_type character varying(20) null,
  quantity numeric(8, 2) not null default 1,
  meal_date timestamp with time zone not null default CURRENT_TIMESTAMP,
  constraint meal_logs_pkey primary key (id),
  constraint meal_logs_item_id_fkey foreign KEY (item_id) references items (id),
  constraint meal_logs_user_id_fkey foreign KEY (user_id) references users (id) on delete CASCADE,
  constraint meal_logs_quantity_check check ((quantity > (0)::numeric))
) TABLESPACE pg_default;